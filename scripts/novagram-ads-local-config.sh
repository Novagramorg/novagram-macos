#!/bin/bash
# Creates Telegram-Mac/NovagramAds.local.xcconfig (git-ignored) for the Novagram ads SDK.
#
# The SDK carries its own hosts and keys; the build only names an environment:
#
#   NOVAGRAM_ADS_ENVIRONMENT  development | production  (dev and prod are accepted too)
#
# Usage:
#   ./scripts/novagram-ads-local-config.sh [development|production]
#   NOVAGRAM_ADS_ENVIRONMENT=production ./scripts/novagram-ads-local-config.sh
#
# Default is development, for local builds. Telegram-Mac/Novagram.xcconfig defaults to production when this file is absent.

set -euo pipefail
cd "$(dirname "$0")/.."

OUT="Telegram-Mac/NovagramAds.local.xcconfig"
value="$(printf '%s' "${1:-${NOVAGRAM_ADS_ENVIRONMENT:-development}}" | tr '[:upper:]' '[:lower:]')"

case "$value" in
    development | dev) environment="development" ;;
    production | prod) environment="production" ;;
    *)
        echo "Environment must be development or production; file not written." >&2
        exit 1
        ;;
esac

{
    echo "// Generated by scripts/novagram-ads-local-config.sh. Git-ignored: do not commit this file."
    echo "NOVAGRAM_ADS_ENVIRONMENT = ${environment}"
} > "$OUT"

echo "Wrote $OUT (environment: ${environment})."
